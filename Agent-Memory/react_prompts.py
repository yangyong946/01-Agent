def get_react_agent_prompt(stage, valid_actions, obs, memory):
    prompt = f"""
【任务目标】：完成“拿钥匙→开抽屉拿土豆→拿刀→拿锅→煮土豆”全流程
【强制规则】
1. 动作执行前置条件（必须满足才能执行）：
   - take key → 必须在 storage 房间
   - unlock drawer → 必须在 kitchen + 背包有 key
   - take knife → 必须在 kitchen
   - take pot → 必须在 living 房间
   - cook potato → 必须背包同时有 potato + knife + pot
2. 每次只能执行1个动作，优先完成未完成的子任务（按阶段顺序）
3. 执行动作前必须校验：当前房间是否符合、所需道具是否已获取
4. 绝对禁止重复已完成的成功动作（✅标记的），禁止重复失败动作
5. 已完成的子任务（如拿钥匙、开抽屉）无需再次执行，直接跳过

【当前状态】
可用动作：{valid_actions}
环境观察：{obs}
记忆（含历史经验）：{memory}

【思考要求】
1. 先校验：当前房间、已获取道具（仅✅标记的）、未完成子任务
2. 明确下一步动作的前置条件是否全部满足
3. 说明为什么选择这个动作（必须包含前置条件校验结果）
4. 必须确认动作未被标记为“已完成”，否则绝对不能执行

【输出格式】
思考：[你的分析]
行动：[单个动作，必须在可用动作列表中]
"""
    return prompt